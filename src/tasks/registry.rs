pub fn tasks() -> &'static [Task] {
    TASKS
}

pub fn by_id(id: &str) -> Option<&'static Task> {
    TASKS.iter().find(|t| t.id == id)
}

/// 지금 동작하는 작업 수와 전체 작업 수.
pub fn progress() -> (usize, usize) {
    let ready = TASKS.iter().filter(|t| t.state == TaskState::Ready).count();
    (ready, TASKS.len())
}
