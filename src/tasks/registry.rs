macro_rules! t {
    (
        $id:literal, $screen:ident, $ms:literal, $state:ident,
        $title:literal, $answers:literal,
        aka [$($a:literal),* $(,)?],
        needs [$($tool:literal),* $(,)?],
        uses [$($c:literal),* $(,)?]
    ) => {
        Task {
            id: $id,
            screen: Screen::$screen,
            title: $title,
            answers: $answers,
            aliases: &[$($a),*],
            tools: &[$($tool),*],
            commands: &[$($c),*],
            state: TaskState::$state,
            milestone: $ms,
        }
    };
}

